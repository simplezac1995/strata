/**
 * Merge scripts/zh-overrides.json into the split dictionaries (upsert keys).
 *
 * The dictionaries are one file per key prefix under src/shared/i18n/dict/<lang>/. This script upserts each override
 * into the file that owns the key's prefix, and regenerates the aggregator index so a brand-new prefix becomes
 * importable. It replaced the old version that rewrote en.ts / zh.ts wholesale — that would have flattened the split
 * back into two monoliths.
 *
 * Run: node scripts/patch-zh-overrides.mjs
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "src/shared/i18n");
const overrides = JSON.parse(readFileSync(path.join(root, "scripts/zh-overrides.json"), "utf8"));

const langDir = (lang) => path.join(src, "dict", lang);
const pascal = (prefix) => prefix.charAt(0).toUpperCase() + prefix.slice(1);

function parseFile(file) {
  const text = readFileSync(file, "utf8");
  const entries = new Map();
  for (const match of text.matchAll(/^  ("(?:\\.|[^"\\])*"): ("(?:\\.|[^"\\])*"),$/gm)) {
    entries.set(JSON.parse(match[1]), JSON.parse(match[2]));
  }
  return entries;
}

function loadLang(lang) {
  const dir = langDir(lang);
  const groups = new Map();
  if (!existsSync(dir)) return groups;
  for (const name of readdirSync(dir)) {
    if (!name.endsWith(".ts") || name === "index.ts") continue;
    groups.set(name.replace(/\.ts$/, ""), parseFile(path.join(dir, name)));
  }
  return groups;
}

function writeLang(lang, groups) {
  const dir = langDir(lang);
  mkdirSync(dir, { recursive: true });
  const prefixes = [...groups.keys()].sort((a, b) => a.localeCompare(b));

  for (const prefix of prefixes) {
    const entries = [...groups.get(prefix).entries()].sort((a, b) => a[0].localeCompare(b[0]));
    writeFileSync(
      path.join(dir, `${prefix}.ts`),
      [
        `// ${lang.toUpperCase()} dictionary slice for the "${prefix}." key prefix.`,
        `// Generated by scripts/patch-zh-overrides.mjs — edit values here, add new keys of the same prefix here.`,
        "",
        `export const ${lang}${pascal(prefix)}: Record<string, string> = {`,
        ...entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`),
        "};",
        "",
      ].join("\n"),
      "utf8",
    );
  }

  writeFileSync(
    path.join(dir, "index.ts"),
    [
      "// Aggregates one dictionary file per key prefix.",
      "// Generated by scripts/patch-zh-overrides.mjs — add the import + spread below when a new prefix file appears.",
      "",
      ...prefixes.map((prefix) => `import { ${lang}${pascal(prefix)} } from "./${prefix}";`),
      "",
      `export const ${lang}: Record<string, string> = {`,
      ...prefixes.map((prefix) => `  ...${lang}${pascal(prefix)},`),
      "};",
      "",
    ].join("\n"),
    "utf8",
  );

  return prefixes.length;
}

const dictionaries = { en: loadLang("en"), zh: loadLang("zh") };
let patched = 0;
for (const [key, fix] of Object.entries(overrides)) {
  const prefix = key.split(".")[0];
  for (const lang of ["en", "zh"]) {
    if (!dictionaries[lang].has(prefix)) dictionaries[lang].set(prefix, new Map());
    dictionaries[lang].get(prefix).set(key, lang === "zh" ? fix.zh : fix.en);
  }
  patched += 1;
}

for (const lang of ["en", "zh"]) {
  console.log(`${lang}: ${writeLang(lang, dictionaries[lang])} prefix files`);
}
console.log(`patched=${patched}`);
