/**
 * Split the admin i18n monoliths (src/shared/i18n/{en,zh}.ts) into one dictionary file per key prefix.
 *
 * Why: en.ts and zh.ts were each ~3,100 lines and every text change had to be found inside a single object, which
 * also made merge conflicts the default. After this, a change touches one small file, and the prefix in the key
 * tells you which file it lives in.
 *
 * The public surface stays the same: en.ts / zh.ts become thin aggregators, so
 * `import { en } from "@/shared/i18n/en"` keeps working.
 *
 * Parsing uses the TypeScript compiler rather than a regex: the dictionaries contain values on continuation lines
 * and escaped quotes, which line-based parsing gets wrong.
 *
 * Run: node scripts/split-i18n.mjs
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const i18nDir = path.join(root, "src/shared/i18n");

/** @param {string} file @param {"en"|"zh"} lang */
function readDictionary(file, lang) {
  const text = readFileSync(file, "utf8");
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  let dictionary = null;

  const visit = (node) => {
    if (
      ts.isVariableDeclaration(node) &&
      node.name.getText(source) === lang &&
      node.initializer &&
      ts.isObjectLiteralExpression(node.initializer)
    ) {
      dictionary = new Map();
      for (const property of node.initializer.properties) {
        if (!ts.isPropertyAssignment(property)) continue;
        const key = property.name.getText(source).replace(/^["']|["']$/g, "");
        let value = null;
        if (
          ts.isStringLiteral(property.initializer) ||
          ts.isNoSubstitutionTemplateLiteral(property.initializer)
        ) {
          value = property.initializer.text;
        }
        dictionary.set(key, value);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);

  if (!dictionary) throw new Error(`no "${lang}" object literal found in ${file}`);
  return dictionary;
}

/** @param {Map<string, string>} dictionary */
function groupByPrefix(dictionary) {
  const groups = new Map();
  for (const [key, value] of dictionary) {
    const prefix = key.split(".")[0];
    if (!groups.has(prefix)) groups.set(prefix, []);
    groups.get(prefix).push([key, value]);
  }
  return new Map([...groups.entries()].sort(([a], [b]) => a.localeCompare(b)));
}

/** @param {string} prefix */
function moduleSuffix(prefix) {
  return prefix.charAt(0).toUpperCase() + prefix.slice(1);
}

/** @param {string} lang @param {string} outDir @param {Map<string, Array<[string,string]>>} groups */
function writeLanguages(lang, outDir, groups) {
  mkdirSync(outDir, { recursive: true });
  const written = [];
  const lines = [];

  for (const [prefix, entries] of groups) {
    const suffix = moduleSuffix(prefix);
    const constant = `${lang}${suffix}`;
    const body = entries
      .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value ?? "")},`)
      .join("\n");
    const content = [
      `// ${lang.toUpperCase()} dictionary slice for the "${prefix}." key prefix.`,
      `// Generated by scripts/split-i18n.mjs — edit values here, add new keys of the same prefix to this file.`,
      ``,
      `export const ${constant}: Record<string, string> = {`,
      body,
      `};`,
      ``,
    ].join("\n");
    writeFileSync(path.join(outDir, `${prefix}.ts`), content, "utf8");
    written.push(prefix);
    lines.push(`import { ${constant} } from "./${prefix}";`);
  }

  const indexContent = [
    `// Aggregates one dictionary file per key prefix.`,
    `// Generated by scripts/split-i18n.mjs — add the import + spread below when a new prefix file appears.`,
    ``,
    ...lines,
    ``,
    `export const ${lang}: Record<string, string> = {`,
    ...written.map((prefix) => `  ...${lang}${moduleSuffix(prefix)},`),
    `};`,
    ``,
  ].join("\n");
  writeFileSync(path.join(outDir, "index.ts"), indexContent, "utf8");

  return written;
}

for (const lang of ["en", "zh"]) {
  const file = path.join(i18nDir, `${lang}.ts`);
  const dictionary = readDictionary(file, lang);
  const groups = groupByPrefix(dictionary);

  const outDir = path.join(i18nDir, "dict", lang);
  mkdirSync(path.dirname(outDir), { recursive: true });
  for (const entry of readdirSync(path.dirname(outDir), { withFileTypes: true })) {
    if (entry.isDirectory() && entry.name === lang)
      rmSync(outDir, { recursive: true, force: true });
  }
  const prefixes = writeLanguages(lang, outDir, groups);

  writeFileSync(
    file,
    [
      `// The ${lang} dictionary lives one file per key prefix under ./dict/${lang}/.`,
      `// This module stays the public export so existing imports keep resolving to "@/shared/i18n/${lang}".`,
      `export { ${lang} } from "./dict/${lang}";`,
      ``,
    ].join("\n"),
    "utf8",
  );

  console.log(
    `${lang}: ${dictionary.size} keys -> ${prefixes.length} files under shared/i18n/dict/${lang}/`,
  );
}

// The verification script used to read zh.ts directly; point it at the split files instead.
const verifyPath = path.join(root, "scripts/verify-i18n.mjs");
if (existsSync(verifyPath)) {
  const original = readFileSync(verifyPath, "utf8");
  const needle = `const zhText = readFileSync(path.join(src, "shared/i18n/zh.ts"), "utf8");`;
  const replacement = [
    `const zhDir = path.join(src, "shared/i18n/dict/zh");`,
    `const zhText = readdirSync(zhDir)`,
    `  .filter((name) => name.endsWith(".ts"))`,
    `  .map((name) => readFileSync(path.join(zhDir, name), "utf8"))`,
    `  .join("\\n");`,
  ].join("\n");
  if (original.includes(needle)) {
    writeFileSync(verifyPath, original.replace(needle, replacement), "utf8");
    console.log("verify-i18n.mjs: now reads the split zh dictionaries");
  } else {
    console.warn("verify-i18n.mjs: expected line not found — check it manually");
  }
}
